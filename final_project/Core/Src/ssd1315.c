/* -----------------------------------------------------------------------
 * 低層：送命令 / 資料
 * ----------------------------------------------------------------------- */
static void oled_cmd(I2C_HandleTypeDef *hi2c, uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};
    HAL_I2C_Master_Transmit(hi2c, SSD1315_ADDR, buf, 2, 50);
}

static void oled_data(I2C_HandleTypeDef *hi2c, uint8_t *data, uint16_t len)
{
    /* SSD1315 支援連續資料傳輸，第一個 byte 是 0x40（Co=0, D/C=1） */
    uint8_t buf[129];
    buf[0] = 0x40;
    memcpy(&buf[1], data, len > 128 ? 128 : len);
    HAL_I2C_Master_Transmit(hi2c, SSD1315_ADDR, buf,
                            (len > 128 ? 128 : len) + 1, 100);
}

/* -----------------------------------------------------------------------
 * 初始化序列（SSD1315 與 SSD1306 相容）
 * ----------------------------------------------------------------------- */
HAL_StatusTypeDef SSD1315_Init(I2C_HandleTypeDef *hi2c)
{
    HAL_Delay(100);  /* 等 OLED 上電穩定 */

    const uint8_t init_seq[] = {
        0xAE,        /* Display OFF */
        0xD5, 0x80,  /* Clock divide / oscillator */
        0xA8, 0x3F,  /* Multiplex ratio 64 */
        0xD3, 0x00,  /* Display offset 0 */
        0x40,        /* Start line 0 */
        0x8D, 0x14,  /* Charge pump ON */
        0x20, 0x00,  /* Memory mode: horizontal */
        0xA1,        /* Segment remap */
        0xC8,        /* COM scan direction */
        0xDA, 0x12,  /* COM pins */
        0x81, 0xCF,  /* Contrast */
        0xD9, 0xF1,  /* Pre-charge */
        0xDB, 0x40,  /* VCOMH deselect */
        0xA4,        /* Display from RAM */
        0xA6,        /* Normal display */
        0xAF,        /* Display ON */
    };

    for (size_t i = 0; i < sizeof(init_seq); i++) {
        oled_cmd(hi2c, init_seq[i]);
    }

    SSD1315_Clear(hi2c);
    return HAL_OK;
}

/* -----------------------------------------------------------------------
 * 清除畫面
 * ----------------------------------------------------------------------- */
void SSD1315_Clear(I2C_HandleTypeDef *hi2c)
{
    uint8_t zeros[128] = {0};
    for (uint8_t page = 0; page < 8; page++) {
        oled_cmd(hi2c, 0xB0 | page);  /* 設定 page */
        oled_cmd(hi2c, 0x00);          /* 低 column */
        oled_cmd(hi2c, 0x10);          /* 高 column */
        oled_data(hi2c, zeros, 128);
    }
}

/* -----------------------------------------------------------------------
 * 設定游標並寫入字串（8×8 字型）
 * ----------------------------------------------------------------------- */
void SSD1315_WriteString(I2C_HandleTypeDef *hi2c,
                         uint8_t col, uint8_t row, const char *str)
{
    /* row = page（0–7），col = 字元欄（0–15） */
    uint8_t pixel_col = col * 8;

    oled_cmd(hi2c, 0xB0 | (row & 0x07));
    oled_cmd(hi2c, 0x00 | (pixel_col & 0x0F));
    oled_cmd(hi2c, 0x10 | (pixel_col >> 4));

    while (*str && col < 16) {
        uint8_t c = (uint8_t)*str;
        if (c < 32 || c > 126) c = 32;  /* 不可見字元→空白 */
        uint8_t glyph[8];
        memcpy(glyph, font8x8[c - 32], 8);
        oled_data(hi2c, glyph, 8);
        str++;
        col++;
    }
}
